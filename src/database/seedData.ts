export async function initializeDatabase(forceReset = false): Promise<void> {
  const usersCount = await db.users.count();

  if (usersCount === 0 || forceReset) {
    if (forceReset) {
      await db.users.clear();
      await db.customers.clear();
      await db.commodities.clear();
      await db.testParameters.clear();
      await db.reports.clear();
      await db.reportRevisions.clear();
      await db.invoices.clear();
      await db.payments.clear();
      await db.companySettings.clear();
      await db.reportSettings.clear();
      await db.billingSettings.clear();
      await db.activityLogs.clear();
    }

    await db.companySettings.put(defaultCompanySettings);
    await db.reportSettings.put(defaultReportSettings);
    await db.billingSettings.put(defaultBillingSettings);

    await db.users.bulkPut(defaultUsers);
    await db.testParameters.bulkPut(defaultTestParameters);
    await db.commodities.bulkPut(defaultCommodities);
    await db.customers.bulkPut(defaultCustomers);
    await db.reports.bulkPut(defaultReports);
    await db.invoices.bulkPut(defaultInvoices);
    await db.payments.bulkPut(defaultPayments);

    await db.activityLogs.add({
      id: 'log-init',
      userId: 'user-admin',
      userName: 'Rahul Sharma (Admin)',
      action: 'SYSTEM_INITIALIZED',
      entityType: 'System',
      entityId: 'init',
      details: 'Demonstration database initialized with realistic laboratory test records.',
      timestamp: new Date().toISOString(),
    });
  }
}
